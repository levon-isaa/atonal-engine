#!/usr/bin/env python3
"""Measure the RENDERER, not the analysis. Opt-in; NOT part of tests/run.py.

    python tests/render_bench.py clock     # is the drawn motion smooth, and by how much
    python tests/render_bench.py morph     # every shape pair's transition, all 72
    python tests/render_bench.py edges     # how rough is the silhouette, and where
    python tests/render_bench.py all

WHY THIS FILE EXISTS. Every measurement in viewer.html had to be rebuilt by hand before it
could be taken, and that cost real accuracy: MORPH's constants were tuned on three shape pairs
out of seventy-two, not because three was thought sufficient but because a fourth meant more
hand-driving. The claims in that file are only as good as the ability to re-run them, and
until now there was no way to.

WHY IT DOES NOT USE A NORMAL BROWSER TAB. requestAnimationFrame is throttled to about 1fps in
a tab the OS considers hidden, and an embedded preview pane can report document.hidden === true
even while it is on screen. Measured there: 19 frames in 20 seconds. Every per-frame number
this file produces would be silently wrong. So it drives its own Chrome over CDP with
background throttling disabled, and asserts document.hidden === false before believing anything.

WHAT IT NEEDS. A server on ATONAL_PORT (default 8770) and Google Chrome. The audio fixture is
generated by tests/fixtures.py and copied into assets/ for the page to fetch, because the
server's static allowlist is deliberately narrow (see _STATIC_DIRS); it is removed again on the
way out, including on failure.

DEPENDENCIES. websocket-client, numpy, Pillow. Unlike the other two suites this one is not
dependency-free, which is the other reason it is not in run.py.
"""
import atexit
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, ROOT)

PORT = int(os.environ.get("ATONAL_PORT", "8770"))
CDP_PORT = int(os.environ.get("ATONAL_CDP_PORT", "9333"))
CHROME = os.environ.get("ATONAL_CHROME",
                        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")


# ------------------------------------------------------------------ CDP driver
class Chrome:
    """Just enough Chrome DevTools Protocol to evaluate JS and read the answer."""

    def __init__(self, port=CDP_PORT):
        import websocket                                   # noqa: F401  (checked early)
        self.port = port
        self.dir = tempfile.mkdtemp(prefix="atonal-bench-")
        self.proc = subprocess.Popen(
            [CHROME,
             "--remote-debugging-port=%d" % port,
             "--user-data-dir=" + self.dir,
             "--no-first-run", "--no-default-browser-check",
             # WITHOUT THESE THREE THE NUMBERS ARE FICTION -- see the module docstring.
             "--disable-background-timer-throttling",
             "--disable-backgrounding-occluded-windows",
             "--disable-renderer-backgrounding",
             "--disable-features=CalculateNativeWinOcclusion",
             "--autoplay-policy=no-user-gesture-required",
             "--mute-audio", "--window-size=1280,800", "--headless=new",
             "about:blank"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.ws = None
        self._id = 0

    def connect(self, url, timeout=40):
        import websocket
        deadline = time.time() + timeout
        last = None
        while time.time() < deadline:
            try:
                tabs = json.load(urllib.request.urlopen(
                    "http://127.0.0.1:%d/json" % self.port, timeout=2))
                page = next((t for t in tabs if t["type"] == "page"), None)
                if page:
                    # suppress_origin: DevTools rejects a WebSocket carrying an Origin header
                    # with 403. The alternative is --remote-allow-origins=*, which is a wider
                    # hole in a debugging endpoint than simply not sending the header.
                    self.ws = websocket.create_connection(
                        page["webSocketDebuggerUrl"], max_size=256 * 1024 * 1024,
                        suppress_origin=True)
                    self.send("Page.enable")
                    self.send("Runtime.enable")
                    self.send("Page.navigate", {"url": url})
                    time.sleep(2.0)
                    return
            except Exception as e:                          # Chrome is still starting
                last = e
                time.sleep(0.4)
        raise RuntimeError("could not attach to Chrome on %d (%s)" % (self.port, last))

    def send(self, method, params=None, timeout=180):
        self._id += 1
        mid = self._id
        self.ws.send(json.dumps({"id": mid, "method": method, "params": params or {}}))
        self.ws.settimeout(timeout)
        while True:
            msg = json.loads(self.ws.recv())
            if msg.get("id") == mid:
                if "error" in msg:
                    raise RuntimeError(msg["error"])
                return msg.get("result")

    def js(self, expr, timeout=180):
        r = self.send("Runtime.evaluate",
                      {"expression": "(async()=>{ %s })()" % expr,
                       "awaitPromise": True, "returnByValue": True,
                       "timeout": timeout * 1000},
                      timeout=timeout + 20)
        if r.get("exceptionDetails"):
            raise RuntimeError(json.dumps(r["exceptionDetails"])[:600])
        return r["result"].get("value")

    def close(self):
        try:
            self.ws.close()
        except Exception:
            pass
        try:
            self.proc.terminate()
            self.proc.wait(timeout=5)
        except Exception:
            self.proc.kill()
        shutil.rmtree(self.dir, ignore_errors=True)


# ------------------------------------------------------------------ page setup
def serve_fixture():
    """Put a known track where the page can fetch it, and take it away afterwards.

    A generated fixture rather than a real file: the bar grid, the section boundaries and the
    tempo are known by construction, so a measurement can be checked against them.
    """
    import fixtures
    path, truth, bpm = fixtures.structure_track()
    dest = os.path.join(ROOT, "assets", "_bench.wav")
    shutil.copy(path, dest)
    atexit.register(lambda: os.path.exists(dest) and os.remove(dest))
    return "/assets/_bench.wav", truth, bpm


def open_viewer(query=""):
    c = Chrome()
    try:
        c.connect("http://127.0.0.1:%d/%s" % (PORT, query))
    except Exception:
        c.close()
        raise
    hidden = c.js("return document.hidden;")
    if hidden:
        c.close()
        raise RuntimeError("document.hidden is true -- rAF would be throttled; refusing to "
                           "report per-frame numbers. See the module docstring.")
    return c


def load_track(c, url, timeout=300):
    c.js("""window.SYNC={};
        const r=await fetch('%s'); const b=await r.blob();
        loadFile(new File([b],'bench.wav',{type:'audio/wav'})); return 1;""" % url)
    deadline = time.time() + timeout
    while time.time() < deadline:
        st = json.loads(c.js("return JSON.stringify({d:!!window.DIRECTOR,"
                             "p:window.SYNC&&window.SYNC.playing});"))
        if st.get("d") and st.get("p"):
            return st
        time.sleep(2)
    raise RuntimeError("track never started playing")


def pin(c):
    """Everything still but the thing under test. Comparing across page loads is void --
    TFREEZE pins the camera and section wherever they happened to be, and the same build has
    measured 0.19 and 1.27 for one quantity on two loads."""
    return c.js("""pause(); window.TFREEZE=40.0; window.QLOCK=true;
        window.POSE={spin:1.0,cam:0.6,tumble:0.4,swirl:0.2};
        await new Promise(r=>setTimeout(r,400)); return 'pinned';""")


# ------------------------------------------------------------------ clock judder
def bench_clock(c, url, secs=25):
    """How smooth is the drawn motion, in degrees and then in pixels?

    Fitted against the WALL clock, not the transport, so the answer does not depend on frame
    cadence -- which is the whole difficulty, since neither a hidden tab nor a headless one
    runs at a steady 60. A local CUBIC absorbs the bar swing, the ladder's rate ramps and any
    real acceleration, leaving only what steps at the frame scale.
    """
    import numpy as np
    load_track(c, url)
    raw = c.js("""
        window.__C=[]; window.__on=true;
        (function tick(){ if(!window.__on) return; const s=window.SYNC;
          if(s&&s.playing) window.__C.push([performance.now(), pos(), s.spin, s.spinOut,
                                            s.tumble, s.swirl]);
          requestAnimationFrame(tick); })();
        await new Promise(r=>setTimeout(r,%d)); window.__on=false;
        return JSON.stringify(window.__C);""" % (secs * 1000), timeout=secs + 90)
    a = np.array(json.loads(raw), dtype=np.float64)
    wall = (a[:, 0] - a[0, 0]) / 1000.0

    def judder(ang, win=0.40, deg=3):
        out, i = [], 0
        while i < len(wall):
            j = np.searchsorted(wall, wall[i] + win)
            if j - i >= deg + 5:
                w = wall[i:j] - wall[i]
                y = ang[i:j]
                out.append((y - np.polyval(np.polyfit(w, y, deg), w)) * 180.0 / np.pi)
            i = j if j > i else i + 1
        return np.concatenate(out) if out else np.array([0.0])

    print("  %d frames over %.1fs (%.1f fps)" % (len(a), wall[-1], len(a) / wall[-1]))
    # the clock itself: residual against a straight line in wall time
    y = a[:, 1] - a[0, 1]
    m, b = np.linalg.lstsq(np.vstack([wall, np.ones_like(wall)]).T, y, rcond=None)[0]
    res = (y - (m * wall + b)) * 1000.0
    d = np.diff(a[:, 1])
    d = d[d > 1e-9]
    q = np.median(d / np.round(d / 0.0053333)) * 1000.0 if len(d) else float("nan")
    print("  clock: slope %.6f (1.0 = no drift), residual rms %.2fms, ptp %.2fms, quantum ~%.3fms"
          % (m, res.std(), res.max() - res.min(), q))
    out = {}
    for name, col in (("formSpin", 2), ("spinOut", 3), ("formTumble", 4), ("formSwirl", 5)):
        r = judder(a[:, col])
        out[name] = r.std()
        print("  %-10s judder %.4f deg rms   p95 %.4f   ptp %.4f"
              % (name, r.std(), np.percentile(np.abs(r), 95), r.max() - r.min()))
    # degrees -> pixels. u_fov is a TRUE vertical FOV (f=0.5/tan(fov/2), uv.y spans +/-0.5),
    # and a spin of alpha moves a surface point at `reach` by reach*alpha, subtending
    # reach*alpha/dist at the camera.
    g = json.loads(c.js("""const cv=document.querySelector('canvas');
        return JSON.stringify({h:cv.height, dpr:devicePixelRatio, reach:frameReach(),
                               dist:CM.dist, fov:CM.fov});"""))
    px_per_rad = (g["h"] / g["dpr"]) / (2.0 * np.arctan(0.5 / (0.5 / np.tan(g["fov"] / 2))))
    scale = (g["reach"] / g["dist"]) * px_per_rad
    print("  geometry: reach %.2f at dist %.2f, fov %.3f -> %.0f px per radian of spin"
          % (g["reach"], g["dist"], g["fov"], scale))
    print("  DRAWN JUDDER %.3f px rms  (sub-pixel is the expected answer; see the note at"
          " the read point in viewer.html)" % (out["spinOut"] * np.pi / 180.0 * scale))
    return out


# ------------------------------------------------------------------ morph sweep
GRAB = """
window.__grab = function(){
  const cv=document.querySelector('canvas'), g=cv.getContext('webgl2');
  const W=256,H=256, x=Math.max(0,(cv.width-W*2)>>1), y=Math.max(0,(cv.height-H*2)>>1);
  const buf=new Uint8Array(W*2*H*2*4);
  g.readPixels(x,y,W*2,H*2,g.RGBA,g.UNSIGNED_BYTE,buf);
  const out=new Float32Array(W*H);
  for(let j=0;j<H;j++) for(let i=0;i<W;i++){
    const o=((j*2)*(W*2)+(i*2))*4;
    out[j*W+i]=buf[o]*0.299+buf[o+1]*0.587+buf[o+2]*0.114; }
  return out; };
window.__sweep = async function(a,b,n){
  window.PAIRPIN=[a,b]; window.MIXPIN=0;
  await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
  const d=[]; let prev=null;
  for(let i=0;i<n;i++){
    window.MIXPIN=i/(n-1);
    await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
    const f=window.__grab();
    if(prev){ let s=0; for(let k=0;k<f.length;k++) s+=Math.abs(f[k]-prev[k]); d.push(s/f.length); }
    prev=f; }
  return d; };
return 'ready';
"""


def bench_morph(c, url, modes=9, n=21):
    """Every ordered shape pair's transition, in ONE page load.

    readPixels off a centred box, not a screenshot: 1512 full-frame PNGs over CDP wedged the
    browser. `lurch` is the worst step-to-step ratio and `evenness` the rate's relative spread;
    neither can separate a lurch from deliberate easing, so they compare curves and are not
    absolute defect measures.
    """
    import numpy as np
    load_track(c, url)
    print("  " + pin(c))
    c.js(GRAB)
    nf = c.js("""const a=window.__grab();
        await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
        const b=window.__grab(); let s=0; for(let k=0;k<a.length;k++) s+=Math.abs(a[k]-b[k]);
        return s/a.length;""")
    print("  noise floor (same pose, two grabs): %.4f levels" % nf)
    res = {}
    for a in range(modes):
        for b in range(modes):
            if a == b:
                continue
            d = np.array(c.js("return await window.__sweep(%d,%d,%d);" % (a, b, n), timeout=120),
                         dtype=np.float64)
            chk = json.loads(c.js("return JSON.stringify({m:window.SYNC.mode,"
                                  "m2:window.SYNC.mode2});"))
            # PAIRPIN silently doing nothing is the failure this whole sweep once produced
            if chk["m"] != a or chk["m2"] != b:
                raise RuntimeError("PAIRPIN did not take for %d->%d: %s" % (a, b, chk))
            if d.size < 3 or d.mean() <= 1e-9:
                continue
            m = d.mean()
            rt = np.maximum(d[1:], 1e-9) / np.maximum(d[:-1], 1e-9)
            res["%d->%d" % (a, b)] = {"lurch": float(max(rt.max(), (1.0 / rt).max())),
                                      "evenness": float(d.std() / m),
                                      "start": float(d[0] / m), "end": float(d[-1] / m)}
    c.js("window.PAIRPIN=null; window.MIXPIN=null; return 1;")
    L = np.array([r["lurch"] for r in res.values()])
    E = np.array([r["evenness"] for r in res.values()])
    print("  %d pairs | lurch  median %.2f p90 %.2f min %.2f max %.2f"
          % (len(res), np.median(L), np.percentile(L, 90), L.min(), L.max()))
    print("  %d pairs | even   median %.3f p90 %.3f max %.3f"
          % (len(res), np.median(E), np.percentile(E, 90), E.max()))
    worst = sorted(res, key=lambda k: -res[k]["lurch"])[:5]
    print("  worst: " + ", ".join("%s %.2f" % (k, res[k]["lurch"]) for k in worst))
    # THE RIG CHECKING ITSELF: the curve is time-symmetric, so a->b and b->a must agree.
    dl = [abs(res[k]["lurch"] - res["%s->%s" % tuple(k.split("->")[::-1])]["lurch"])
          for k in res if "%s->%s" % tuple(k.split("->")[::-1]) in res]
    print("  symmetry check (a->b vs b->a): worst lurch disagreement %.4f" % max(dl))
    return res


# ------------------------------------------------------------------ entry
# ------------------------------------------------------------------ silhouette quality
# The default framebuffer is undefined once the frame has been presented, so a readPixels from
# Runtime.evaluate returns a cleared buffer -- measured as every arm of a sweep coming back
# byte-identical with a whole-box RMSE of exactly 0.000, which is what sent this down a blind
# alley the first time. The read has to happen in the SAME TASK as the draw. frame() reschedules
# itself at its top, so wrapping requestAnimationFrame survives, and the grab runs after frame()
# returns and before the compositor takes it.
_GRAB_HOOK = """
  const _raf=window.requestAnimationFrame.bind(window);
  window.requestAnimationFrame=cb=>_raf(t=>{ cb(t);
    if(window.__WANT){ const W=glc.width,H=glc.height;
      const x0=(W>>1)-320,y0=(H>>1)-220,w=640,h=440;
      const px=new Uint8Array(w*h*4);
      gl.bindFramebuffer(gl.FRAMEBUFFER,null);
      gl.readPixels(x0,y0,w,h,gl.RGBA,gl.UNSIGNED_BYTE,px);
      let s=''; for(let i=0;i<w*h;i++) s+=String.fromCharCode(px[i*4]);
      window.__GOT={w:w,h:h,r:btoa(s)}; window.__WANT=false; } });
  return 1;
"""
_GRAB = """
  window.QLOCK=true; rscale=%f; DX.sharpen=%f; applyScale();
  await new Promise(r=>setTimeout(r,700));
  window.__GOT=null; window.__WANT=true;
  for(let i=0;i<300 && !window.__GOT;i++) await new Promise(r=>setTimeout(r,20));
  return JSON.stringify(window.__GOT);
"""


def _grab(c, scale, sharpen=0.0):
    import base64
    import numpy as np
    d = json.loads(c.js(_GRAB % (scale, sharpen), timeout=90))
    a = np.frombuffer(base64.b64decode(d["r"]), np.uint8).astype(float)
    return a.reshape(d["h"], d["w"])


def _boxblur(a, k):
    """A control, not a filter: if plain blur scored well the metric below would be measuring
    softness rather than reconstruction, and could not arbitrate between two AA filters."""
    import numpy as np
    from numpy.lib.stride_tricks import sliding_window_view
    g = np.exp(-((np.arange(k) - k // 2) ** 2) / (2 * (k / 4.0) ** 2))
    g /= g.sum()
    w = sliding_window_view(np.pad(a, k // 2, mode="edge"), (k, k))
    return (w * np.outer(g, g)).sum(axis=(2, 3))


def bench_edges(c, url):
    """How far is the silhouette from a properly resolved one, and does the error have a
    direction to it?

    Ground truth is a 2.2x march resolved by the post pass to the SAME canvas size, so this is
    a like-for-like comparison of output pixels and not of buffers. Every arm comes from one
    page load behind TFREEZE: comparing across loads is void, because the pause lands at a
    different point in the track and the section, material and contrast all move with it.
    """
    import numpy as np
    load_track(c, url)
    pin(c)
    c.js(_GRAB_HOOK)
    ref = _grab(c, 2.20)
    gx = np.diff(ref, axis=1)[:-1, :]
    gy = np.diff(ref, axis=0)[:, :-1]
    band = (np.abs(gx) + np.abs(gy)) > 18.0
    ang = np.degrees(np.arctan2(np.abs(gx), np.abs(gy) + 1e-9))   # 0 = horizontal edge
    naxis = band & ((ang < 20) | (ang >= 70))
    diag = band & (ang >= 20) & (ang < 70)
    print("  silhouette band %.2f%% of box   near-axis %d px   diagonal %d px"
          % (100.0 * band.mean(), naxis.sum(), diag.sum()))

    def rmse(img, m):
        e = (img - ref)[:-1, :-1]
        return float(np.sqrt((e[m] ** 2).mean()))

    print("\n  rscale   all edges   near-axis   diagonal")
    for sc in (0.80, 0.92, 1.00, 1.10, 1.25):
        img = _grab(c, sc)
        print("   %.2f     %7.3f     %7.3f    %7.3f"
              % (sc, rmse(img, band), rmse(img, naxis), rmse(img, diag)))
    print("\n  The resolve switches from FXAA to a real 4-tap tent above ssRatio 1.05, which is")
    print("  why 1.00 -> 1.10 is a step and not a slope. See the governor's HEADROOM/SS_MIN.")

    raw = _grab(c, 1.00)
    print("\n  metric control -- blur is not reconstruction, so it must score WORSE:")
    for k in (3, 5, 7):
        print("    native + %dx%d gaussian   %7.3f" % (k, k, rmse(_boxblur(raw, k), band)))
    print("    native, unblurred        %7.3f" % rmse(raw, band))


def main():
    what = (sys.argv[1] if len(sys.argv) > 1 else "all").lower()
    try:
        urllib.request.urlopen("http://127.0.0.1:%d/health" % PORT, timeout=3).read()
    except Exception:
        print("no server on %d -- start it with:  python server.py" % PORT)
        return 2
    if not os.path.exists(CHROME):
        print("Chrome not found at %s (set ATONAL_CHROME)" % CHROME)
        return 2
    url, truth, bpm = serve_fixture()
    print("fixture: %s  (%.0f bpm, boundaries %s)" % (url, bpm, truth))
    rc = 0
    for name, fn, q in (("clock", bench_clock, ""), ("morph", bench_morph, "?readback"),
                        ("edges", bench_edges, "")):
        if what not in ("all", name):
            continue
        print("\n== %s ==" % name)
        c = open_viewer(q)
        try:
            fn(c, url)
        except Exception as e:
            print("  FAILED: %s" % str(e)[:400])
            rc = 1
        finally:
            c.close()
    return rc


if __name__ == "__main__":
    sys.exit(main())
