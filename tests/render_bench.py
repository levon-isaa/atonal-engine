# ------------------------------------------------------------------ CDP driver
class Chrome:
    """Just enough Chrome DevTools Protocol to evaluate JS and read the answer."""

    def __init__(self, port=CDP_PORT):
        import websocket                                   # noqa: F401  (checked early)
        self.port = port
        self.dir = tempfile.mkdtemp(prefix="atonal-bench-")
        self.proc = subprocess.Popen(
            [CHROME,
             "--remote-debugging-port=%d" % port,
             "--user-data-dir=" + self.dir,
             "--no-first-run", "--no-default-browser-check",
             # WITHOUT THESE THREE THE NUMBERS ARE FICTION -- see the module docstring.
             "--disable-background-timer-throttling",
             "--disable-backgrounding-occluded-windows",
             "--disable-renderer-backgrounding",
             "--disable-features=CalculateNativeWinOcclusion",
             "--autoplay-policy=no-user-gesture-required",
             "--mute-audio", "--window-size=1280,800", "--headless=new",
             "about:blank"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.ws = None
        self._id = 0

    def connect(self, url, timeout=40):
        import websocket
        deadline = time.time() + timeout
        last = None
        while time.time() < deadline:
            try:
                tabs = json.load(urllib.request.urlopen(
                    "http://127.0.0.1:%d/json" % self.port, timeout=2))
                page = next((t for t in tabs if t["type"] == "page"), None)
                if page:
                    # suppress_origin: DevTools rejects a WebSocket carrying an Origin header
                    # with 403. The alternative is --remote-allow-origins=*, which is a wider
                    # hole in a debugging endpoint than simply not sending the header.
                    self.ws = websocket.create_connection(
                        page["webSocketDebuggerUrl"], max_size=256 * 1024 * 1024,
                        suppress_origin=True)
                    self.send("Page.enable")
                    self.send("Runtime.enable")
                    self.send("Page.navigate", {"url": url})
                    time.sleep(2.0)
                    return
            except Exception as e:                          # Chrome is still starting
                last = e
                time.sleep(0.4)
        raise RuntimeError("could not attach to Chrome on %d (%s)" % (self.port, last))

    def send(self, method, params=None, timeout=180):
        self._id += 1
        mid = self._id
        self.ws.send(json.dumps({"id": mid, "method": method, "params": params or {}}))
        self.ws.settimeout(timeout)
        while True:
            msg = json.loads(self.ws.recv())
            if msg.get("id") == mid:
                if "error" in msg:
                    raise RuntimeError(msg["error"])
                return msg.get("result")

    def js(self, expr, timeout=180):
        r = self.send("Runtime.evaluate",
                      {"expression": "(async()=>{ %s })()" % expr,
                       "awaitPromise": True, "returnByValue": True,
                       "timeout": timeout * 1000},
                      timeout=timeout + 20)
        if r.get("exceptionDetails"):
            raise RuntimeError(json.dumps(r["exceptionDetails"])[:600])
        return r["result"].get("value")

    def close(self):
        try:
            self.ws.close()
        except Exception:
            pass
        try:
            self.proc.terminate()
            self.proc.wait(timeout=5)
        except Exception:
            self.proc.kill()
        shutil.rmtree(self.dir, ignore_errors=True)


