def serve_fixture():
    """Put a known track where the page can fetch it, and take it away afterwards.

    A generated fixture rather than a real file: the bar grid, the section boundaries and the
    tempo are known by construction, so a measurement can be checked against them.
    """
    import fixtures
    path, truth, bpm = fixtures.structure_track()
    dest = os.path.join(ROOT, "assets", "_bench.wav")
    shutil.copy(path, dest)
    atexit.register(lambda: os.path.exists(dest) and os.remove(dest))
    return "/assets/_bench.wav", truth, bpm


def open_viewer(query=""):
    c = Chrome()
    try:
        c.connect("http://127.0.0.1:%d/%s" % (PORT, query))
    except Exception:
        c.close()
        raise
    hidden = c.js("return document.hidden;")
    if hidden:
        c.close()
        raise RuntimeError("document.hidden is true -- rAF would be throttled; refusing to "
                           "report per-frame numbers. See the module docstring.")
    return c


def load_track(c, url, timeout=300):
    c.js("""window.SYNC={};
        const r=await fetch('%s'); const b=await r.blob();
        loadFile(new File([b],'bench.wav',{type:'audio/wav'})); return 1;""" % url)
    deadline = time.time() + timeout
    while time.time() < deadline:
        st = json.loads(c.js("return JSON.stringify({d:!!window.DIRECTOR,"
                             "p:window.SYNC&&window.SYNC.playing});"))
        if st.get("d") and st.get("p"):
            return st
        time.sleep(2)
    raise RuntimeError("track never started playing")


def pin(c):
    """Everything still but the thing under test. Comparing across page loads is void --
    TFREEZE pins the camera and section wherever they happened to be, and the same build has
    measured 0.19 and 1.27 for one quantity on two loads."""
    return c.js("""pause(); window.TFREEZE=40.0; window.QLOCK=true;
        window.POSE={spin:1.0,cam:0.6,tumble:0.4,swirl:0.2};
        await new Promise(r=>setTimeout(r,400)); return 'pinned';""")


# ------------------------------------------------------------------ clock judder
def bench_clock(c, url, secs=25):
    """How smooth is the drawn motion, in degrees and then in pixels?

    Fitted against the WALL clock, not the transport, so the answer does not depend on frame
    cadence -- which is the whole difficulty, since neither a hidden tab nor a headless one
    runs at a steady 60. A local CUBIC absorbs the bar swing, the ladder's rate ramps and any
    real acceleration, leaving only what steps at the frame scale.
    """
    import numpy as np
    load_track(c, url)
    raw = c.js("""
        window.__C=[]; window.__on=true;
        (function tick(){ if(!window.__on) return; const s=window.SYNC;
          if(s&&s.playing) window.__C.push([performance.now(), pos(), s.spin, s.spinOut,
                                            s.tumble, s.swirl, s.swirlOut||0]);
          requestAnimationFrame(tick); })();
        await new Promise(r=>setTimeout(r,%d)); window.__on=false;
        return JSON.stringify(window.__C);""" % (secs * 1000), timeout=secs + 90)
    a = np.array(json.loads(raw), dtype=np.float64)
    wall = (a[:, 0] - a[0, 0]) / 1000.0

    def judder(ang, win=0.40, deg=3):
        out, i = [], 0
        while i < len(wall):
            j = np.searchsorted(wall, wall[i] + win)
            if j - i >= deg + 5:
                w = wall[i:j] - wall[i]
                y = ang[i:j]
                out.append((y - np.polyval(np.polyfit(w, y, deg), w)) * 180.0 / np.pi)
            i = j if j > i else i + 1
        return np.concatenate(out) if out else np.array([0.0])

    print("  %d frames over %.1fs (%.1f fps)" % (len(a), wall[-1], len(a) / wall[-1]))
    # the clock itself: residual against a straight line in wall time
    y = a[:, 1] - a[0, 1]
    m, b = np.linalg.lstsq(np.vstack([wall, np.ones_like(wall)]).T, y, rcond=None)[0]
    res = (y - (m * wall + b)) * 1000.0
    d = np.diff(a[:, 1])
    d = d[d > 1e-9]
    q = np.median(d / np.round(d / 0.0053333)) * 1000.0 if len(d) else float("nan")
    print("  clock: slope %.6f (1.0 = no drift), residual rms %.2fms, ptp %.2fms, quantum ~%.3fms"
          % (m, res.std(), res.max() - res.min(), q))
    out = {}
    # swirlOut IS THE DOMINANT DRAWN ROTATION when FACE.on, which is the default: the continuous
    # turn was moved onto the plate's own normal so it cannot present the edge, and spinOut is
    # then only the bounded lean. Measuring spinOut alone would report the judder of the small
    # motion and miss the large one.
    for name, col in (("formSpin", 2), ("spinOut", 3), ("formTumble", 4), ("formSwirl", 5),
                      ("swirlOut", 6)):
        r = judder(a[:, col])
        out[name] = r.std()
        print("  %-10s judder %.4f deg rms   p95 %.4f   ptp %.4f"
              % (name, r.std(), np.percentile(np.abs(r), 95), r.max() - r.min()))
    # degrees -> pixels. u_fov is a TRUE vertical FOV (f=0.5/tan(fov/2), uv.y spans +/-0.5),
    # and a spin of alpha moves a surface point at `reach` by reach*alpha, subtending
    # reach*alpha/dist at the camera.
    g = json.loads(c.js("""const cv=document.querySelector('canvas');
        return JSON.stringify({h:cv.height, dpr:devicePixelRatio, reach:frameReach(),
                               dist:CM.dist, fov:CM.fov});"""))
    px_per_rad = (g["h"] / g["dpr"]) / (2.0 * np.arctan(0.5 / (0.5 / np.tan(g["fov"] / 2))))
    scale = (g["reach"] / g["dist"]) * px_per_rad
    print("  geometry: reach %.2f at dist %.2f, fov %.3f -> %.0f px per radian of spin"
          % (g["reach"], g["dist"], g["fov"], scale))
    # The LARGER of the two form rotations, because which one carries the turn depends on FACE:
    # spinOut when the free three-axis motion is on, swirlOut when the plate is held face-on.
    worst = max(out["spinOut"], out.get("swirlOut", 0.0))
    print("  DRAWN JUDDER %.3f px rms  (sub-pixel is the expected answer; see the note at"
          " the read point in viewer.html)" % (worst * np.pi / 180.0 * scale))
    return out


# ------------------------------------------------------------------ morph sweep
GRAB = """
window.__grab = function(){
  const cv=document.querySelector('canvas'), g=cv.getContext('webgl2');
  const W=256,H=256, x=Math.max(0,(cv.width-W*2)>>1), y=Math.max(0,(cv.height-H*2)>>1);
  const buf=new Uint8Array(W*2*H*2*4);
  g.readPixels(x,y,W*2,H*2,g.RGBA,g.UNSIGNED_BYTE,buf);
  const out=new Float32Array(W*H);
  for(let j=0;j<H;j++) for(let i=0;i<W;i++){
    const o=((j*2)*(W*2)+(i*2))*4;
    out[j*W+i]=buf[o]*0.299+buf[o+1]*0.587+buf[o+2]*0.114; }
  return out; };
window.__sweep = async function(a,b,n){
  window.PAIRPIN=[a,b]; window.MIXPIN=0;
  await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
  const d=[]; let prev=null;
  for(let i=0;i<n;i++){
    window.MIXPIN=i/(n-1);
    await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
    const f=window.__grab();
    if(prev){ let s=0; for(let k=0;k<f.length;k++) s+=Math.abs(f[k]-prev[k]); d.push(s/f.length); }
    prev=f; }
  return d; };
return 'ready';
"""


def bench_morph(c, url, modes=9, n=21):
    """Every ordered shape pair's transition, in ONE page load.

    readPixels off a centred box, not a screenshot: 1512 full-frame PNGs over CDP wedged the
    browser. `lurch` is the worst step-to-step ratio and `evenness` the rate's relative spread;
    neither can separate a lurch from deliberate easing, so they compare curves and are not
    absolute defect measures.
    """
    import numpy as np
    load_track(c, url)
    print("  " + pin(c))
    c.js(GRAB)
    nf = c.js("""const a=window.__grab();
        await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
        const b=window.__grab(); let s=0; for(let k=0;k<a.length;k++) s+=Math.abs(a[k]-b[k]);
        return s/a.length;""")
    print("  noise floor (same pose, two grabs): %.4f levels" % nf)
    res = {}
    for a in range(modes):
        for b in range(modes):
            if a == b:
                continue
            d = np.array(c.js("return await window.__sweep(%d,%d,%d);" % (a, b, n), timeout=120),
                         dtype=np.float64)
            chk = json.loads(c.js("return JSON.stringify({m:window.SYNC.mode,"
                                  "m2:window.SYNC.mode2});"))
            # PAIRPIN silently doing nothing is the failure this whole sweep once produced
            if chk["m"] != a or chk["m2"] != b:
                raise RuntimeError("PAIRPIN did not take for %d->%d: %s" % (a, b, chk))
            if d.size < 3 or d.mean() <= 1e-9:
                continue
            m = d.mean()
            rt = np.maximum(d[1:], 1e-9) / np.maximum(d[:-1], 1e-9)
            res["%d->%d" % (a, b)] = {"lurch": float(max(rt.max(), (1.0 / rt).max())),
                                      "evenness": float(d.std() / m),
                                      "start": float(d[0] / m), "end": float(d[-1] / m)}
    c.js("window.PAIRPIN=null; window.MIXPIN=null; return 1;")
    L = np.array([r["lurch"] for r in res.values()])
    E = np.array([r["evenness"] for r in res.values()])
    print("  %d pairs | lurch  median %.2f p90 %.2f min %.2f max %.2f"
          % (len(res), np.median(L), np.percentile(L, 90), L.min(), L.max()))
    print("  %d pairs | even   median %.3f p90 %.3f max %.3f"
          % (len(res), np.median(E), np.percentile(E, 90), E.max()))
    worst = sorted(res, key=lambda k: -res[k]["lurch"])[:5]
    print("  worst: " + ", ".join("%s %.2f" % (k, res[k]["lurch"]) for k in worst))
    # THE RIG CHECKING ITSELF: the curve is time-symmetric, so a->b and b->a must agree.
    dl = [abs(res[k]["lurch"] - res["%s->%s" % tuple(k.split("->")[::-1])]["lurch"])
          for k in res if "%s->%s" % tuple(k.split("->")[::-1]) in res]
    print("  symmetry check (a->b vs b->a): worst lurch disagreement %.4f" % max(dl))
    return res


