#!/usr/bin/env python3
"""Measure the RENDERER, not the analysis. Opt-in; NOT part of tests/run.py.

    python tests/render_bench.py clock     # is the drawn motion smooth, and by how much
    python tests/render_bench.py morph     # every shape pair's transition, all 72
    python tests/render_bench.py edges     # how rough is the silhouette, and where
    python tests/render_bench.py costs     # what each pass actually costs, by ablation
    python tests/render_bench.py director  # the Director's timing rules, asserted
    python tests/render_bench.py all

WHY THIS FILE EXISTS. Every measurement in viewer.html had to be rebuilt by hand before it
could be taken, and that cost real accuracy: MORPH's constants were tuned on three shape pairs
out of seventy-two, not because three was thought sufficient but because a fourth meant more
hand-driving. The claims in that file are only as good as the ability to re-run them, and
until now there was no way to.

WHY IT DOES NOT USE A NORMAL BROWSER TAB. requestAnimationFrame is throttled to about 1fps in
a tab the OS considers hidden, and an embedded preview pane can report document.hidden === true
even while it is on screen. Measured there: 19 frames in 20 seconds. Every per-frame number
this file produces would be silently wrong. So it drives its own Chrome over CDP with
background throttling disabled, and asserts document.hidden === false before believing anything.

WHAT IT NEEDS. A server on ATONAL_PORT (default 8770) and Google Chrome. The audio fixture is
generated by tests/fixtures.py and copied into assets/ for the page to fetch, because the
server's static allowlist is deliberately narrow (see _STATIC_DIRS); it is removed again on the
way out, including on failure.

DEPENDENCIES. websocket-client, numpy, Pillow. Unlike the other two suites this one is not
dependency-free, which is the other reason it is not in run.py.
"""
