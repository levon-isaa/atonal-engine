GRAB = """
window.__grab = function(){
  const cv=document.querySelector('canvas'), g=cv.getContext('webgl2');
  const W=256,H=256, x=Math.max(0,(cv.width-W*2)>>1), y=Math.max(0,(cv.height-H*2)>>1);
  const buf=new Uint8Array(W*2*H*2*4);
  g.readPixels(x,y,W*2,H*2,g.RGBA,g.UNSIGNED_BYTE,buf);
  const out=new Float32Array(W*H);
  for(let j=0;j<H;j++) for(let i=0;i<W;i++){
    const o=((j*2)*(W*2)+(i*2))*4;
    out[j*W+i]=buf[o]*0.299+buf[o+1]*0.587+buf[o+2]*0.114; }
  return out; };
window.__sweep = async function(a,b,n){
  window.PAIRPIN=[a,b]; window.MIXPIN=0;
  await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
  const d=[]; let prev=null;
  for(let i=0;i<n;i++){
    window.MIXPIN=i/(n-1);
    await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
    const f=window.__grab();
    if(prev){ let s=0; for(let k=0;k<f.length;k++) s+=Math.abs(f[k]-prev[k]); d.push(s/f.length); }
    prev=f; }
  return d; };
return 'ready';
"""


def bench_morph(c, url, modes=9, n=21):
    """Every ordered shape pair's transition, in ONE page load.

    readPixels off a centred box, not a screenshot: 1512 full-frame PNGs over CDP wedged the
    browser. `lurch` is the worst step-to-step ratio and `evenness` the rate's relative spread;
    neither can separate a lurch from deliberate easing, so they compare curves and are not
    absolute defect measures.
    """
    import numpy as np
    load_track(c, url)
    print("  " + pin(c))
    c.js(GRAB)
    nf = c.js("""const a=window.__grab();
        await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
        const b=window.__grab(); let s=0; for(let k=0;k<a.length;k++) s+=Math.abs(a[k]-b[k]);
        return s/a.length;""")
    print("  noise floor (same pose, two grabs): %.4f levels" % nf)
    res = {}
    for a in range(modes):
        for b in range(modes):
            if a == b:
                continue
            d = np.array(c.js("return await window.__sweep(%d,%d,%d);" % (a, b, n), timeout=120),
                         dtype=np.float64)
            chk = json.loads(c.js("return JSON.stringify({m:window.SYNC.mode,"
                                  "m2:window.SYNC.mode2});"))
            # PAIRPIN silently doing nothing is the failure this whole sweep once produced
            if chk["m"] != a or chk["m2"] != b:
                raise RuntimeError("PAIRPIN did not take for %d->%d: %s" % (a, b, chk))
            if d.size < 3 or d.mean() <= 1e-9:
                continue
            m = d.mean()
            rt = np.maximum(d[1:], 1e-9) / np.maximum(d[:-1], 1e-9)
            res["%d->%d" % (a, b)] = {"lurch": float(max(rt.max(), (1.0 / rt).max())),
                                      "evenness": float(d.std() / m),
                                      "start": float(d[0] / m), "end": float(d[-1] / m)}
    c.js("window.PAIRPIN=null; window.MIXPIN=null; return 1;")
    L = np.array([r["lurch"] for r in res.values()])
    E = np.array([r["evenness"] for r in res.values()])
    print("  %d pairs | lurch  median %.2f p90 %.2f min %.2f max %.2f"
          % (len(res), np.median(L), np.percentile(L, 90), L.min(), L.max()))
    print("  %d pairs | even   median %.3f p90 %.3f max %.3f"
          % (len(res), np.median(E), np.percentile(E, 90), E.max()))
    worst = sorted(res, key=lambda k: -res[k]["lurch"])[:5]
    print("  worst: " + ", ".join("%s %.2f" % (k, res[k]["lurch"]) for k in worst))
    # THE RIG CHECKING ITSELF: the curve is time-symmetric, so a->b and b->a must agree.
    dl = [abs(res[k]["lurch"] - res["%s->%s" % tuple(k.split("->")[::-1])]["lurch"])
          for k in res if "%s->%s" % tuple(k.split("->")[::-1]) in res]
    print("  symmetry check (a->b vs b->a): worst lurch disagreement %.4f" % max(dl))
    return res


