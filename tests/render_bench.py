def _wait_for(url, timeout=25):
    end = time.time() + timeout
    while time.time() < end:
        try:
            urllib.request.urlopen(url, timeout=2).read()
            return True
        except Exception:
            time.sleep(0.3)
    return False


def _goto(c, url, settle=2.2):
    c.send("Page.navigate", {"url": url})
    time.sleep(settle)


