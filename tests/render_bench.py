# ------------------------------------------------------------------ the filter cell
# WHY. "Filter cell is still too much, it looks like a mess." The cell that reaches the shader
# is not the slider: it is the slider times dpr times dprScale times a contrast term times a
# music term, so any judgement about where the subject survives has to be made on the PRODUCT,
# in device pixels. FCELLPIN in viewer.html pins exactly that, so this sweeps the real quantity.
#
# THE METRIC IS SILHOUETTE RECOVERY, not similarity to the unfiltered frame. A halftone is
# supposed to look nothing like its source close up -- that is what a halftone is -- so scoring
# resemblance would condemn the filter at every setting. What the complaint is actually about is
# the SUBJECT disappearing: past some cell the dots stop describing a shape. So the reference is
# the unfiltered frame's foreground mask, and the score is how much of that mask you can still
# recover from the filtered frame after a FIXED 3px blur -- fixed, and deliberately not scaled
# with the cell, because a blur that grows with the cell would hand every setting the same score.
#
# AND THE REFERENCE IS _mask, WHICH IS A LUMA SPLIT. Read its docstring: it is not tracking the
# form, so "the subject covers 64% of the box" in this arm's output means the luma split, not the
# shape. This is the second reason nothing in the filter commit rests on these numbers.


def _mask(a):
    """A LUMA SPLIT, NOT A SUBJECT MASK, and the difference has cost real time twice.

    Otsu picks the threshold that best separates the histogram into two halves. On these frames
    the background is a lit gradient covering the whole plate, so the split it finds is usually
    inside the BACKGROUND, not between the form and everything else. Measured: on the filter
    arm's reference frame it called 64-65% of the box "subject", and asked for a bounding box it
    returns the whole canvas on every frame -- which is what it should return, for a mask that is
    not tracking the form.

    So it is fine for what it was written for -- comparing one filtered frame against another at
    the SAME pose, where whatever it selects it selects consistently -- and it is wrong for any
    question about where the form is or how big it is.

    USE window.DBGMASK FOR THAT, which is a real subject mask and which I previously recorded
    here as not being one. Wrong: the scene pass stores the ray's depth on a HIT and the
    sentinel 99 on a MISS -- the sentinel exists so a ray pointing away cannot report itself as
    the nearest possible hit -- so DBGMASK's `alpha < 17` means "hit the form" and renders it
    white. Read it as `pixel > 128`. Reading it the other way round selects the background and
    reports the form as 78-92% of the frame, which is what it did.
    """
    import numpy as np
    h, _ = np.histogram(a, bins=256, range=(0, 256))
    p = h / max(h.sum(), 1)
    om, cut = -1.0, 128
    w0 = 0.0
    m0 = 0.0
    mt = float((np.arange(256) * p).sum())
    for t in range(1, 255):
        w0 += p[t]
        m0 += t * p[t]
        w1 = 1.0 - w0
        if w0 < 1e-6 or w1 < 1e-6:
            continue
        v = (mt * w0 - m0) ** 2 / (w0 * w1)
        if v > om:
            om, cut = v, t
    return a > cut


def bench_filter(c, url):
    """Where does the subject stop surviving the filter, in device pixels?"""
    import numpy as np
    load_track(c, url)
    pin(c)
    c.js(_GRAB_HOOK)
    c.js("window.FCELLPIN=null; setCtl('selFilt','0'); return 1;")
    ref = _mask(_grab(c, 1.0))
    grow = _boxblur(ref.astype(float), 25)
    BAND = (grow > 0.02) & (grow < 0.98)      # a fixed collar around the true silhouette
    print("  reference subject covers %.1f%% of the box; the scored band is %.1f%% of it"
          % (100.0 * ref.mean(), 100.0 * BAND.mean()))

    names = {"1": "Halftone dots", "2": "Halftone lines", "3": "Pixelate", "6": "ASCII"}
    cells = [3, 4, 6, 8, 10, 12, 14, 16, 20, 24, 30, 40]
    out = {}
    for m, label in names.items():
        c.js("setCtl('selFilt','%s'); return 1;" % m)
        row = []
        for px in cells:
            c.js("window.FCELLPIN=%d; return 1;" % px)
            g = _boxblur(_grab(c, 1.0), 3)
            got = _mask(g)
            # SCORED IN A BAND AROUND THE SILHOUETTE, not over the whole box. The interior of a
            # halftoned form is dots either way and agrees with the reference by accident, which
            # swamped the first version of this: whole-box IoU fell from 0.81 to 0.56 across a
            # 13x range of cell with no knee anywhere, and ASCII scored HIGHER as it got coarser.
            # The damage the complaint is about is at the edge -- the outline stops describing a
            # shape -- so the score is IoU restricted to a fixed 12px band around the true edge.
            row.append(float((got & ref)[BAND].sum()) / max(float((got | ref)[BAND].sum()), 1.0))
        out[label] = row
        print("  %-15s " % label + " ".join("%5.2f" % v for v in row))
    print("  %-15s " % "cell (device px)" + " ".join("%5d" % v for v in cells))
    return out


# ------------------------------------------------------------------ resolution, fold controlled
# FOLD DUTY IS THE CONFOUND, and it took three wrong conclusions in one session to see it. How
# much of a run the kaleidoscope is open varies from 12% to 93% with the music, and it moves the
# share of frames above the resolve threshold by more than any governor change measured here.
# Two readings taken that way said a change did nothing and made oscillation three times worse;
# with the duty held equal the same change was better on every count.
#
# So this arm never measures the Director's fold. It pins the fold ON and OFF in turn and reports
# both, which is the only comparison that means anything across builds -- and the two together
# say more than the mixed number ever did: OFF is what the machine can hold, ON is what it holds
# when the most expensive thing in the renderer is running.
def bench_quality(c, url, secs=70):
    """Effective resolution with the fold pinned, which is the only way it compares across runs."""
    import numpy as np
    fails = []

    def check(name, ok, detail=""):
        print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, ("   " + detail) if detail else ""))
        if not ok:
            fails.append(name)

    out = {}
    for tier in ("high", "ultra"):
        for fold in ("off", "on"):
            # A FRESH PAGE PER CONFIGURATION. The first version of this arm measured all four in
            # one load and every one of them inherited the previous governor's ssCeil, shaScale
            # and dprScale -- it reported Ultra at p05 0.70 and 36 reversals where a clean load
            # of the same build reads 0.88 and 12. The note at the top of this file says an old
            # tab is not a clean build; it is just as true of an old tier.
            _goto(c, "http://127.0.0.1:%d/" % PORT, settle=2.5)
            load_track(c, url)
            c.js("applyTier('%s'); setCtl('selKal','%s'); return 1;" % (tier, fold))
            d = json.loads(c.js("""
              const S=[]; let t0=performance.now(); const cv=document.querySelector('canvas');
              const tick=()=>{ S.push([performance.now()-t0, RW/Math.max(1,cv.width), rscale, kalAmt]);
                if(performance.now()-t0 < %d) requestAnimationFrame(tick); };
              requestAnimationFrame(tick);
              await new Promise(r=>setTimeout(r,%d));
              return JSON.stringify(S);""" % (secs * 1000, secs * 1000 + 2000), timeout=secs + 60))
            a = np.array(d, dtype=float)
            late = a[a[:, 0] > 15000]
            ss, rs, kal = late[:, 1], late[:, 2], late[:, 3]
            ch = np.where(np.abs(np.diff(rs)) > 1e-6)[0]
            st = np.sign(np.diff(rs)[ch])
            rev = int((np.diff(st) != 0).sum()) if len(st) > 1 else 0
            out[(tier, fold)] = (float(np.median(ss)), 100.0 * (ss > 1.05).mean(),
                                 float(np.percentile(rs, 5)), rev, 100.0 * (kal > 0.35).mean())
            print("  %-5s fold %-3s | ss p50 %.2f | above the tent %5.1f%% | rscale p05 %.2f | reversals %2d | duty %5.1f%%"
                  % (tier, fold, *out[(tier, fold)]))

    # With the fold OFF the machine is not being asked for anything unusual, so a tier that
    # cannot hold its own resolve threshold there has a problem that is not the music's fault.
    for tier in ("high", "ultra"):
        check("%s clears the resolve threshold with the fold off" % tier,
              out[(tier, "off")][1] >= 80.0, "%.1f%% of frames" % out[(tier, "off")][1])
    # NOT ASSERTED: that Ultra keeps the native floor its own note promises. It does not -- the
    # fold relaxes the floor by KFL and the march reaches 0.84 there, on both tiers. That was
    # written as an assertion first, failed, and the code was right: trading the shadow budget
    # for march pixels during a fold improves the number, it does not restore the promise. A
    # test that asserts something the code has never done is a test that is always red.
    # The 1Hz oscillator the banded branch warns about would be roughly one reversal per tick,
    # about 110 over this window. The bar is set where that is caught and ordinary adaptation is
    # not; the gap between the tiers is printed above rather than asserted, because it is a known
    # open difference and not a regression.
    for tier in ("high", "ultra"):
        check("%s does not hunt while folded" % tier, out[(tier, "on")][3] <= 45,
              "%d reversals in %ds" % (out[(tier, "on")][3], secs - 15))
    check("the march never goes below the fold-relaxed floor",
          min(out[(t, "on")][2] for t in ("high", "ultra")) >= 0.70 - 0.02,
          "worst rscale p05 %.2f against a floor of 0.70"
          % min(out[(t, "on")][2] for t in ("high", "ultra")))
    if fails:
        raise AssertionError("quality failures: " + ", ".join(fails))


