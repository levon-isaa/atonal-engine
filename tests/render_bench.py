# ------------------------------------------------------------------ the filter cell
# WHY. "Filter cell is still too much, it looks like a mess." The cell that reaches the shader
# is not the slider: it is the slider times dpr times dprScale times a contrast term times a
# music term, so any judgement about where the subject survives has to be made on the PRODUCT,
# in device pixels. FCELLPIN in viewer.html pins exactly that, so this sweeps the real quantity.
#
# THE METRIC IS SILHOUETTE RECOVERY, not similarity to the unfiltered frame. A halftone is
# supposed to look nothing like its source close up -- that is what a halftone is -- so scoring
# resemblance would condemn the filter at every setting. What the complaint is actually about is
# the SUBJECT disappearing: past some cell the dots stop describing a shape. So the reference is
# the unfiltered frame's foreground mask, and the score is how much of that mask you can still
# recover from the filtered frame after a FIXED 3px blur -- fixed, and deliberately not scaled
# with the cell, because a blur that grows with the cell would hand every setting the same score.
#
# AND THE REFERENCE IS _mask, WHICH IS A LUMA SPLIT. Read its docstring: it is not tracking the
# form, so "the subject covers 64% of the box" in this arm's output means the luma split, not the
# shape. This is the second reason nothing in the filter commit rests on these numbers.


def _mask(a):
    """A LUMA SPLIT, NOT A SUBJECT MASK, and the difference has cost real time twice.

    Otsu picks the threshold that best separates the histogram into two halves. On these frames
    the background is a lit gradient covering the whole plate, so the split it finds is usually
    inside the BACKGROUND, not between the form and everything else. Measured: on the filter
    arm's reference frame it called 64-65% of the box "subject", and asked for a bounding box it
    returns the whole canvas on every frame -- which is what it should return, for a mask that is
    not tracking the form.

    So it is fine for what it was written for -- comparing one filtered frame against another at
    the SAME pose, where whatever it selects it selects consistently -- and it is wrong for any
    question about where the form is or how big it is. There is no ready subject mask in the
    viewer either: the scene pass writes alpha 99 on a surface hit and the ray distance
    otherwise, so DBGMASK's `alpha < 17` is a DEPTH mask and puts the far background on the same
    side as the form. Isolating the subject would mean a new debug mode (alpha == 99), which is
    worth adding the first time a measurement actually needs one.
    """
    import numpy as np
    h, _ = np.histogram(a, bins=256, range=(0, 256))
    p = h / max(h.sum(), 1)
    om, cut = -1.0, 128
    w0 = 0.0
    m0 = 0.0
    mt = float((np.arange(256) * p).sum())
    for t in range(1, 255):
        w0 += p[t]
        m0 += t * p[t]
        w1 = 1.0 - w0
        if w0 < 1e-6 or w1 < 1e-6:
            continue
        v = (mt * w0 - m0) ** 2 / (w0 * w1)
        if v > om:
            om, cut = v, t
    return a > cut


def bench_filter(c, url):
    """Where does the subject stop surviving the filter, in device pixels?"""
    import numpy as np
    load_track(c, url)
    pin(c)
    c.js(_GRAB_HOOK)
    c.js("window.FCELLPIN=null; setCtl('selFilt','0'); return 1;")
    ref = _mask(_grab(c, 1.0))
    grow = _boxblur(ref.astype(float), 25)
    BAND = (grow > 0.02) & (grow < 0.98)      # a fixed collar around the true silhouette
    print("  reference subject covers %.1f%% of the box; the scored band is %.1f%% of it"
          % (100.0 * ref.mean(), 100.0 * BAND.mean()))

    names = {"1": "Halftone dots", "2": "Halftone lines", "3": "Pixelate", "6": "ASCII"}
    cells = [3, 4, 6, 8, 10, 12, 14, 16, 20, 24, 30, 40]
    out = {}
    for m, label in names.items():
        c.js("setCtl('selFilt','%s'); return 1;" % m)
        row = []
        for px in cells:
            c.js("window.FCELLPIN=%d; return 1;" % px)
            g = _boxblur(_grab(c, 1.0), 3)
            got = _mask(g)
            # SCORED IN A BAND AROUND THE SILHOUETTE, not over the whole box. The interior of a
            # halftoned form is dots either way and agrees with the reference by accident, which
            # swamped the first version of this: whole-box IoU fell from 0.81 to 0.56 across a
            # 13x range of cell with no knee anywhere, and ASCII scored HIGHER as it got coarser.
            # The damage the complaint is about is at the edge -- the outline stops describing a
            # shape -- so the score is IoU restricted to a fixed 12px band around the true edge.
            row.append(float((got & ref)[BAND].sum()) / max(float((got | ref)[BAND].sum()), 1.0))
        out[label] = row
        print("  %-15s " % label + " ".join("%5.2f" % v for v in row))
    print("  %-15s " % "cell (device px)" + " ".join("%5d" % v for v in cells))
    return out


# ------------------------------------------------------------------ director rules
# WHY THESE ARE HERE. One session changed about ten of the Director's behaviours -- the ladder's
# order, the pacing, the phrase lock, the "a boundary is not a reason" gate, the fold's duty --
# and nothing covered any of them. tests/run.py never opens viewer.html, so every one of those
# rules could be undone by an edit and no suite would notice. These assert the rules that are
# cheap to check from a recording of real playback: WHEN a change is allowed to happen, not what
# it looks like.
#
# On the generated fixture, not a real upload: 128s of 8 sections at 120bpm, boundaries known by
# construction at 16s intervals, which is 8 bars -- so a section boundary is also a phrase
# boundary and the phrase rule is satisfiable rather than accidentally impossible.
_DIR_REC = """
  window.__L=[]; window.__PH=0; window.__D=[]; let lastShape=null;
  window.__A={n:0,held:0,open:0,shut:0,inMorph:0,kalIn:0,kalOut:0,pm:0,step:0,stepSecs:4,
              vocabFolded:99,vocabOpen:99};
  const rec=()=>{
    // EVERY DECISION, not every visible change. chooseMode writes __SHAPE on each call and
    // updates the energy the gate compares against -- including calls that return the shape
    // already showing and fire nothing. Testing consecutive CHANGES therefore skips over those
    // and measures a pair the rule was never applied to, which is what made this fail against
    // correct code.
    if(window.__SHAPE && window.__SHAPE!==lastShape){
      lastShape=window.__SHAPE;
      window.__D.push({t:pos(), e:window.__SHAPE.energy, held:!!window.__SHAPE.held});
    }
    // Aggregates accumulated IN PAGE rather than shipping every frame: a 126s run is ~7500
    // frames and only these summaries are wanted.
    {
      const A=window.__A;
      A.n++;
      if(kalHeld) A.held++;
      if(kalAmt>0.35) A.open++;
      if(kalAmt<0.02) A.shut++;
      if(phase===1){ A.inMorph++; A.kalIn+=kalAmt;
                     const st=mix-A.pm; if(st>0 && st>A.step){ A.step=st; A.stepSecs=morphSecs; } }
      else { A.kalOut+=kalAmt; }
      A.pm=mix;
      if(typeof allowedModes==='function'){
        const al=allowedModes().length;
        if(kalHeld && al<A.vocabFolded) A.vocabFolded=al;
        if(!kalHeld && al<A.vocabOpen) A.vocabOpen=al;
      }
    }
    if(phase===1 && window.__PH===0){
      const s=window.__SHAPE||{};
      window.__L.push({t:pos(), from:mode, to:mode2, e:s.energy,
                       bar:swBarK, anch:swPhAnchor, beats:morphBeats(),
                       secs:morphSecs, held:kalHeld?1:0});
    }
    window.__PH=phase;
    if(pos()<%f) requestAnimationFrame(rec);
  };
  requestAnimationFrame(rec);
  await new Promise(r=>setTimeout(r,%d));
  const db=(dbSet?Array.from(dbSet):[]);
  return JSON.stringify({ev:window.__L, dec:window.__D, agg:window.__A, db:db, grid:PHRASE_GRID,
    foldMin:FOLD_MIN, dtCap:MORPH_DT_CAP,
    minSecs:REFORM_MIN_SECS, minDE:REFORM_MIN_DE, idle:REFORM_IDLE_SECS,
    maxBars:(typeof REFORM_MAX_BARS==='number'?REFORM_MAX_BARS:-1), maxWait:REFORM_MAX_WAIT,
    pace:pace(), fast:MORPH_SECS.fast, slow:MORPH_SECS.slow,
    duty:KAL_DUTY, bpm:(director&&director.tempo&&director.tempo.bpm)||0});
"""


def bench_director(c, url):
    """The Director's timing rules, asserted against real playback."""
    import numpy as np
    load_track(c, url)
    # 126s covers the fixture, which is 128s long. A real track is longer, and the things
    # worth watching for are not all in its first two minutes -- the irregular bars that
    # broke the wait budget sit at 135s and 200s of the 176bpm upload. ATONAL_BENCH_SECS
    # opens the window; the run costs about that much wall clock, so it is not the default.
    secs = float(os.environ.get("ATONAL_BENCH_SECS", "126"))
    d = json.loads(c.js(_DIR_REC % (secs, int(secs * 1000) + 4000), timeout=secs + 90))
    ev, db = d["ev"], np.array(sorted(d["db"]))
    bpm, grid = d["bpm"], d["grid"]
    beat = 60.0 / max(bpm, 1e-6)
    fails = []

    def check(name, ok, detail=""):
        print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, ("   " + detail) if detail else ""))
        if not ok:
            fails.append(name)

    print("  %d shape changes in %.0fs at %.1f bpm, phrase grid %d bars"
          % (len(ev), secs, bpm, grid))
    if len(ev) < 2:
        check("enough changes to judge", False, "got %d; the rules cannot be tested" % len(ev))
        raise AssertionError("director: too few changes to assert anything")

    # 1. every change lands on a real downbeat
    if len(db):
        off = [float(np.min(np.abs(db - e["t"]))) for e in ev]
        check("changes land on a downbeat", max(off) < beat * 0.5,
              "worst %.3fs against a %.3fs beat" % (max(off), beat))
    else:
        check("downbeat grid present", False)

    # 2. and on a phrase boundary. The wait budget is allowed to release one that has waited
    #    it out, so this asserts the RULE holds for the great majority rather than every one.
    pb = [((e["bar"] - e["anch"]) % grid + grid) % grid for e in ev]
    onp = sum(1 for x in pb if x == 0)
    check("changes land on a phrase boundary", onp >= max(1, int(0.8 * len(pb))),
          "%d of %d on bar 0 of the %d-bar grid" % (onp, len(pb), grid))

    # 3. no transition runs faster than the range that exists to bound it
    short = [e for e in ev if e["secs"] < d["fast"] - 1e-6]
    check("transition is never shorter than MORPH_SECS.fast", not short,
          "fastest %.2fs against a floor of %.2fs" % (min(e["secs"] for e in ev), d["fast"]))

    # 4. the spacing floor, halved at a section boundary, which is documented and deliberate
    gaps = np.diff([e["t"] for e in ev])
    floor = d["minSecs"] * d["pace"] * 0.5
    check("spacing respects the floor", len(gaps) == 0 or gaps.min() >= floor - 0.05,
          "tightest %.1fs against %.1fs (half of %.1f x pace %.2f)"
          % (gaps.min() if len(gaps) else 0, floor, d["minSecs"], d["pace"]))

    # 5. every DECISION answered a move in the music, unless the idle lapse let it through.
    #    Decisions, not visible changes: the gate compares against the energy of the last call
    #    to chooseMode, and a call that returns the shape already showing fires nothing but
    #    still moves that reference.
    dec = d.get("dec") or []
    bad = 0
    for i in range(1, len(dec)):
        dE = abs(dec[i]["e"] - dec[i - 1]["e"])
        if dE < d["minDE"] and (dec[i]["t"] - dec[i - 1]["t"]) < d["idle"]:
            bad += 1
    check("every decision had a musical reason", bad == 0,
          "%d of %d under dE %.3f without the idle lapse" % (bad, max(len(dec) - 1, 0), d["minDE"]))

    # 6. the fold is an accent, not the resting state -- BUT ONLY WHERE THERE ARE ENOUGH
    #    CHANGES TO SAY SO. This read `held <= 0.9` over however many changes a run happened to
    #    produce, which on a 126s window is three. Three Bernoulli samples against a duty of
    #    0.38 land all-folded by chance often enough that the same unchanged code gave 33% and
    #    then 100% on consecutive runs: a red that means nothing. Rule 7 below measures the same
    #    duty over every frame -- 7143 of them -- and is the assertion to trust. This one only
    #    adds whether the fold is open at CHANGES specifically, which needs n where d**n is
    #    rarer than the failure is worth: at 0.38 that is 8.
    held = float(np.mean([e["held"] for e in ev])) if ev else 0.0
    if len(ev) >= 8:
        check("fold is not pinned open at every change", held <= 0.9,
              "open at %.0f%% of %d changes, duty target %.2f" % (100 * held, len(ev), d["duty"]))
    else:
        check("fold is not pinned open at every change", True,
              "(only %d changes: %.0f%% open, too few to tell from chance -- see rule 7)"
              % (len(ev), 100 * held))

    # ---- the fold and the morph, which this session also changed and nothing covered ----
    A = d.get("agg") or {}
    n = max(A.get("n", 0), 1)
    print("  fold and transition, over %d frames" % n)

    # 7. the fold is an accent. The duty is a target the energy threshold is calibrated to, so
    #    this is a wide band -- it is checking that the mechanism works, not that a track hits
    #    a number. Before 2fa6da9 this read 66% against a 22% target.
    held = A.get("held", 0) / n
    check("fold duty is near its target", held <= d["duty"] * 2.0 + 0.05,
          "held %.0f%% against a target of %.0f%%" % (100 * held, 100 * d["duty"]))

    # 8. and it actually shuts. It never did: measured at 0.0% before the deadband fix, because
    #    an exponential approach to zero plus a deadband strands it just above.
    check("fold reaches fully closed", A.get("shut", 0) / n > 0.05,
          "%.0f%% of frames under kalAmt 0.02" % (100 * A.get("shut", 0) / n))

    # 9. and it gets out of the way of a shape change (efc33f8)
    if A.get("inMorph", 0) > 30 and (n - A.get("inMorph", 0)) > 30:
        kin = A.get("kalIn", 0) / A["inMorph"]
        kout = A.get("kalOut", 0) / (n - A["inMorph"])
        check("fold ducks during a transition", kin <= kout + 0.02,
              "mean kalAmt %.3f inside against %.3f outside" % (kin, kout))
    else:
        check("fold ducks during a transition", True, "(too few morph frames to judge)")

    # 10. a stall may not become a jump (4c90428). The cap is on dt, so the bound on one
    #     frame's mix step is MORPH_DT_CAP / that transition's length, plus a little slack for
    #     the frame the cap itself lands on.
    if A.get("step", 0) > 0:
        bound = d["dtCap"] / max(A.get("stepSecs", 4.0), 0.2)
        check("no single frame jumps the transition", A["step"] <= bound * 1.15,
              "worst step %.5f against a bound of %.5f" % (A["step"], bound))
    else:
        check("no single frame jumps the transition", True, "(no transition observed)")

    # 11. the vocabulary never collapses below the floor a folded passage is guaranteed
    vf = A.get("vocabFolded", 99)
    if vf < 99:
        check("folded vocabulary respects FOLD_MIN", vf >= d["foldMin"],
              "smallest allowed set while folded was %d, floor %d" % (vf, d["foldMin"]))
    else:
        check("folded vocabulary respects FOLD_MIN", True, "(fold never held)")

    # 12. the wait budget is counted in DOWNBEATS. This one is a structural check, not a
    #     behavioural one, and it is here because the behavioural version does not work: the
    #     bug it guards against shows up on 2 arrivals in 714 of the 176bpm upload, so a run
    #     that watches five changes would catch a revert about 1.4% of the time. Measured over
    #     every beat of all four analyses on hand, simulating both rules against the real beat
    #     grids: off-grid landings 2/714 and 2/751 under a beat budget, 0 under a bar count,
    #     for 2 extra beats of worst-case wait. A beat budget cannot be made correct -- a
    #     phrase's length in beats is not known until it is over -- so the assertion is on the
    #     shape of the rule rather than on an outcome it only rarely changes.
    check("the wait budget is counted in bars, not beats",
          d.get("maxBars") == grid and d.get("maxWait") >= grid * 11,
          "escape at %s bars, strand guard at %s beats" % (d.get("maxBars"), d.get("maxWait")))

    if fails:
        raise AssertionError("director rules failed: " + ", ".join(fails))


