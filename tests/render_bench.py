def bench_shape(c, url):
    """Two things that have to be CONTINUOUS, and were not.

    Neither is a look: both are quantities that move on their own while a track plays, and the
    code treated them as if they stood still. The form's scale rides the section energy and the
    motion patch; the material's roughness is eased toward a target every frame and the Print and
    Poster rolls change material by themselves. So an AO kernel fixed in world units, and a
    reflection path chosen by a hard threshold on roughness, both turn a smooth sweep into a
    visible step. These assert that neither does.
    """
    import numpy as np
    fails = []

    def check(name, ok, detail=""):
        print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, ("   " + detail) if detail else ""))
        if not ok:
            fails.append(name)

    load_track(c, url)
    pin(c)
    c.js(_GRAB_HOOK)

    # ---- AO is a fraction of the form, so its contribution cannot depend on the form's size
    scales = (0.50, 0.65, 0.80, 1.00, 1.20, 1.45, 1.60)
    got, cover = [], []
    for s in scales:
        c.js("window.FSCALE=%f; return 1;" % s)
        on = _grab(c, 1.00)
        c.js("DXS.ao=0; return 1;")
        off = _grab(c, 1.00)
        c.js("DXS.ao=1; return 1;")
        c.js("window.DBGMASK=1; return 1;")
        m = _grab(c, 1.00) > 128
        c.js("window.DBGMASK=0; return 1;")
        cover.append(float(m.mean()))
        d = np.abs(on - off)
        got.append(float(d[m].mean()) if m.sum() > 500 else float(d.mean()))
    c.js("window.FSCALE=0; return 1;")
    # DID THE PIN DO ANYTHING? Run against a build without u_fsPin, window.FSCALE is just a
    # property nobody reads: every row then measures the identical frame, the spread comes out at
    # 0% and the check passes while having measured NOTHING. That is worse than no check, and it
    # is what this arm did the first time it was pointed at the old build. The form's share of the
    # box runs about 10% to 66% across this sweep, so if it does not move, the pin is not landing.
    if max(cover) - min(cover) < 0.10:
        raise AssertionError(
            "window.FSCALE did not change the form's size (subject %.1f%%-%.1f%% of the box). "
            "The pin is missing or ignored, so the AO sweep below would measure one frame seven "
            "times." % (100 * min(cover), 100 * max(cover)))
    print("  AO contribution by form scale: " +
          "  ".join("%.2f:%.1f" % (s, v) for s, v in zip(scales, got)))
    spread = (max(got) - min(got)) / max(1e-6, float(np.mean(got)))
    # Fixed radii measured 18.49 down to 10.70 and back to 12.46 across this range -- a 73%
    # spread. Scaled, 10.92 to 12.76, 17%. The bar is set between the two: the subject also grows
    # from 10% to 66% of the box over this sweep, so the population being averaged is not the
    # same at both ends and exact invariance is not on offer.
    check("AO does not change strength with the form's size", spread <= 0.35,
          "spread %.0f%% of the mean, against 73%% with the kernel fixed in world units"
          % (100 * spread))

    # ---- and the traced reflection fades in rather than switching on
    c.js("""for(const o of [MAT,MATT]){o.metal=1.0;o.reflect=1.0;o.rough=0.30;}
            FIN.rghMix=0;FINT.rghMix=0;window.WEAR.amt=0; return 1;""")
    xs = [0.48, 0.50, 0.52, 0.54, 0.56, 0.58, 0.60]
    imgs = {}
    for x in xs:
        c.js("MAT.rough=%f; MATT.rough=%f; return 1;" % (x, x))
        imgs[x] = _grab(c, 1.00)
    steps = {}
    for a, b in zip(xs, xs[1:]):
        d = np.abs(imgs[b] - imgs[a])
        steps[(a, b)] = (float(d.mean()), float((d > 8).mean()))
    print("  consecutive 0.02 roughness steps, mean |d| / share moving >8 levels:")
    for (a, b), (mn, sh) in steps.items():
        print("    %.2f -> %.2f   %6.3f   %6.3f%%" % (a, b, mn, 100 * sh))
    at = steps[(0.54, 0.56)]
    others = [v for k, v in steps.items() if k != (0.54, 0.56)]
    ref = float(np.median([o[0] for o in others]))
    # The gate sat at rgh 0.55. Before: 3.124 mean against a 0.75 median elsewhere, and 10.3% of
    # the frame moving more than 8 levels against 0.03% either side. MAT and MATT are both pinned
    # because MAT is eased toward MATT every frame -- setting only one of them measures the decay
    # back to the old value, which cost a whole wrong reading here.
    check("the traced reflection has no step at the roughness gate", at[0] <= 2.0 * ref,
          "the 0.54-0.56 step is %.3f against a %.3f median elsewhere (was 3.124 vs 0.75)"
          % (at[0], ref))
    check("and no part of the frame jumps across it", at[1] <= 0.01,
          "%.3f%% of pixels move more than 8 levels (was 10.31%%)" % (100 * at[1]))

    if fails:
        raise AssertionError("shape/reflection continuity failed: " + ", ".join(fails))


def bench_director(c, url):
    """The Director's timing rules, asserted against real playback."""
    import numpy as np
    load_track(c, url)
    # 126s covers the fixture, which is 128s long. A real track is longer, and the things
    # worth watching for are not all in its first two minutes -- the irregular bars that
    # broke the wait budget sit at 135s and 200s of the 176bpm upload. ATONAL_BENCH_SECS
    # opens the window; the run costs about that much wall clock, so it is not the default.
    secs = float(os.environ.get("ATONAL_BENCH_SECS", "126"))
    d = json.loads(c.js(_DIR_REC % (secs, int(secs * 1000) + 4000), timeout=secs + 90))
    ev, db = d["ev"], np.array(sorted(d["db"]))
    bpm, grid = d["bpm"], d["grid"]
    beat = 60.0 / max(bpm, 1e-6)
    fails = []

    def check(name, ok, detail=""):
        print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, ("   " + detail) if detail else ""))
        if not ok:
            fails.append(name)

    print("  %d shape changes in %.0fs at %.1f bpm, phrase grid %d bars"
          % (len(ev), secs, bpm, grid))
    if len(ev) < 2:
        check("enough changes to judge", False, "got %d; the rules cannot be tested" % len(ev))
        raise AssertionError("director: too few changes to assert anything")

    # 1. every change lands on a real downbeat
    if len(db):
        off = [float(np.min(np.abs(db - e["t"]))) for e in ev]
        check("changes land on a downbeat", max(off) < beat * 0.5,
              "worst %.3fs against a %.3fs beat" % (max(off), beat))
    else:
        check("downbeat grid present", False)

    # 2. and on a phrase boundary. The wait budget is allowed to release one that has waited
    #    it out, so this asserts the RULE holds for the great majority rather than every one.
    pb = [((e["bar"] - e["anch"]) % grid + grid) % grid for e in ev]
    onp = sum(1 for x in pb if x == 0)
    check("changes land on a phrase boundary", onp >= max(1, int(0.8 * len(pb))),
          "%d of %d on bar 0 of the %d-bar grid" % (onp, len(pb), grid))

    # 3. no transition runs faster than the range that exists to bound it
    short = [e for e in ev if e["secs"] < d["fast"] - 1e-6]
    check("transition is never shorter than MORPH_SECS.fast", not short,
          "fastest %.2fs against a floor of %.2fs" % (min(e["secs"] for e in ev), d["fast"]))

    # 4. the spacing floor, halved at a section boundary, which is documented and deliberate
    gaps = np.diff([e["t"] for e in ev])
    floor = d["minSecs"] * d["pace"] * 0.5
    check("spacing respects the floor", len(gaps) == 0 or gaps.min() >= floor - 0.05,
          "tightest %.1fs against %.1fs (half of %.1f x pace %.2f)"
          % (gaps.min() if len(gaps) else 0, floor, d["minSecs"], d["pace"]))

    # 5. every DECISION answered a move in the music, unless the idle lapse let it through.
    #    Decisions, not visible changes: the gate compares against the energy of the last call
    #    to chooseMode, and a call that returns the shape already showing fires nothing but
    #    still moves that reference.
    dec = d.get("dec") or []
    bad = 0
    for i in range(1, len(dec)):
        dE = abs(dec[i]["e"] - dec[i - 1]["e"])
        if dE < d["minDE"] and (dec[i]["t"] - dec[i - 1]["t"]) < d["idle"]:
            bad += 1
    check("every decision had a musical reason", bad == 0,
          "%d of %d under dE %.3f without the idle lapse" % (bad, max(len(dec) - 1, 0), d["minDE"]))

    # 6. the fold is an accent, not the resting state -- BUT ONLY WHERE THERE ARE ENOUGH
    #    CHANGES TO SAY SO. This read `held <= 0.9` over however many changes a run happened to
    #    produce, which on a 126s window is three. Three Bernoulli samples against a duty of
    #    0.38 land all-folded by chance often enough that the same unchanged code gave 33% and
    #    then 100% on consecutive runs: a red that means nothing. Rule 7 below measures the same
    #    duty over every frame -- 7143 of them -- and is the assertion to trust. This one only
    #    adds whether the fold is open at CHANGES specifically, which needs n where d**n is
    #    rarer than the failure is worth: at 0.38 that is 8.
    held = float(np.mean([e["held"] for e in ev])) if ev else 0.0
    if len(ev) >= 8:
        check("fold is not pinned open at every change", held <= 0.9,
              "open at %.0f%% of %d changes, duty target %.2f" % (100 * held, len(ev), d["duty"]))
    else:
        check("fold is not pinned open at every change", True,
              "(only %d changes: %.0f%% open, too few to tell from chance -- see rule 7)"
              % (len(ev), 100 * held))

    # ---- the fold and the morph, which this session also changed and nothing covered ----
    A = d.get("agg") or {}
    n = max(A.get("n", 0), 1)
    print("  fold and transition, over %d frames" % n)

    # 7. the fold is an accent. The duty is a target the energy threshold is calibrated to, so
    #    this is a wide band -- it is checking that the mechanism works, not that a track hits
    #    a number. Before 2fa6da9 this read 66% against a 22% target.
    held = A.get("held", 0) / n
    check("fold duty is near its target", held <= d["duty"] * 2.0 + 0.05,
          "held %.0f%% against a target of %.0f%%" % (100 * held, 100 * d["duty"]))

    # 8. and it actually shuts. It never did: measured at 0.0% before the deadband fix, because
    #    an exponential approach to zero plus a deadband strands it just above.
    check("fold reaches fully closed", A.get("shut", 0) / n > 0.05,
          "%.0f%% of frames under kalAmt 0.02" % (100 * A.get("shut", 0) / n))

    # 9. and it gets out of the way of a shape change (efc33f8)
    if A.get("inMorph", 0) > 30 and (n - A.get("inMorph", 0)) > 30:
        kin = A.get("kalIn", 0) / A["inMorph"]
        kout = A.get("kalOut", 0) / (n - A["inMorph"])
        check("fold ducks during a transition", kin <= kout + 0.02,
              "mean kalAmt %.3f inside against %.3f outside" % (kin, kout))
    else:
        check("fold ducks during a transition", True, "(too few morph frames to judge)")

    # 10. a stall may not become a jump (4c90428). The cap is on dt, so the bound on one
    #     frame's mix step is MORPH_DT_CAP / that transition's length, plus a little slack for
    #     the frame the cap itself lands on.
    if A.get("step", 0) > 0:
        bound = d["dtCap"] / max(A.get("stepSecs", 4.0), 0.2)
        check("no single frame jumps the transition", A["step"] <= bound * 1.15,
              "worst step %.5f against a bound of %.5f" % (A["step"], bound))
    else:
        check("no single frame jumps the transition", True, "(no transition observed)")

    # 11. the vocabulary never collapses below the floor a folded passage is guaranteed
    vf = A.get("vocabFolded", 99)
    if vf < 99:
        check("folded vocabulary respects FOLD_MIN", vf >= d["foldMin"],
              "smallest allowed set while folded was %d, floor %d" % (vf, d["foldMin"]))
    else:
        check("folded vocabulary respects FOLD_MIN", True, "(fold never held)")

    # 12. the wait budget is counted in DOWNBEATS. This one is a structural check, not a
    #     behavioural one, and it is here because the behavioural version does not work: the
    #     bug it guards against shows up on 2 arrivals in 714 of the 176bpm upload, so a run
    #     that watches five changes would catch a revert about 1.4% of the time. Measured over
    #     every beat of all four analyses on hand, simulating both rules against the real beat
    #     grids: off-grid landings 2/714 and 2/751 under a beat budget, 0 under a bar count,
    #     for 2 extra beats of worst-case wait. A beat budget cannot be made correct -- a
    #     phrase's length in beats is not known until it is over -- so the assertion is on the
    #     shape of the rule rather than on an outcome it only rarely changes.
    check("the wait budget is counted in bars, not beats",
          d.get("maxBars") == grid and d.get("maxWait") >= grid * 11,
          "escape at %s bars, strand guard at %s beats" % (d.get("maxBars"), d.get("maxWait")))

    if fails:
        raise AssertionError("director rules failed: " + ", ".join(fails))


def main():
    what = (sys.argv[1] if len(sys.argv) > 1 else "all").lower()
    try:
        urllib.request.urlopen("http://127.0.0.1:%d/health" % PORT, timeout=3).read()
    except Exception:
        print("no server on %d -- start it with:  python server.py" % PORT)
        return 2
    if not os.path.exists(CHROME):
        print("Chrome not found at %s (set ATONAL_CHROME)" % CHROME)
        return 2
    # A REAL TRACK WHEN ONE IS OFFERED. The generated fixture is right for the structural arms
    # -- its bar grid and section boundaries are known by construction, and its downbeat grid is
    # OFFSET from its sections, which is exactly the property that caught the phrase lock only
    # covering one of two call sites. But fixtures do lie about material: this one peaks mid-bar
    # where real music peaks on the beat, so a rule that holds here is not yet known to hold.
    # ATONAL_BENCH_TRACK points any arm at a file in assets/ instead; a track already in the
    # analysis cache costs nothing to re-run.
    #     ATONAL_BENCH_TRACK=/assets/mine.mp3 python tests/render_bench.py director
    real = os.environ.get("ATONAL_BENCH_TRACK", "").strip()
    if real:
        url, truth, bpm = real, None, 0
        print("track: %s  (given by ATONAL_BENCH_TRACK, not the fixture)" % url)
    else:
        url, truth, bpm = serve_fixture()
        print("fixture: %s  (%.0f bpm, boundaries %s)" % (url, bpm, truth))
    rc = 0
    for name, fn, q in (("clock", bench_clock, ""), ("morph", bench_morph, "?readback"),
                        ("edges", bench_edges, ""), ("costs", bench_costs, ""),
                        ("filter", bench_filter, "?readback"),
                        ("motion", bench_motion, ""),
                        ("quality", bench_quality, ""),
                        ("site", bench_site, ""),
                        ("shape", bench_shape, ""),
                        ("export", bench_export, ""),
                        ("director", bench_director, "")):
        if what not in ("all", name):
            continue
        print("\n== %s ==" % name)
        c = open_viewer(q)
        try:
            fn(c, url)
        except Exception as e:
            print("  FAILED: %s" % str(e)[:400])
            rc = 1
        finally:
            c.close()
    return rc


if __name__ == "__main__":
    sys.exit(main())
